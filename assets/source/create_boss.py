def catalog_text(manifests: list[BossManifest]) -> str:
    ids = ", ".join(json.dumps(manifest.boss_id) for manifest in manifests)
    paths = "\n".join(
        f"\t{json.dumps(manifest.boss_id)}: "
        f"{json.dumps('res://game/enemies/boss/definitions/' + manifest.boss_id + '.tres')},"
        for manifest in manifests
    )
    return f"""{GENERATED_HEADER}
class_name BossCatalog
extends RefCounted

const ORDER := [{ids}]
const PATHS := {{
{paths}
}}

static var _cache: Dictionary = {{}}


static func ids() -> PackedStringArray:
\treturn PackedStringArray(ORDER)


static func has(id: String) -> bool:
\treturn PATHS.has(id)


static func definition(id: String) -> BossDefinition:
\tif not PATHS.has(id):
\t\treturn null
\tif not _cache.has(id):
\t\tvar loaded := load(String(PATHS[id])) as BossDefinition
\t\tif loaded == null or not loaded.valid() or loaded.boss_id != id:
\t\t\tpush_error("Boss definition '%s' is invalid" % id)
\t\t\t_cache[id] = null
\t\telse:
\t\t\t_cache[id] = loaded
\treturn _cache[id] as BossDefinition
"""


def write_or_check(path: Path, content: str, check: bool) -> bool:
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == content:
        return True
    if check:
        print(f"out of date: {_relative(path)}")
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {_relative(path)}")
    return True


def clean_or_check_stale(
    directory: Path,
    pattern: str,
    expected: set[Path],
    check: bool,
) -> bool:
    if not directory.exists():
        return True
    ok = True
    for path in sorted(directory.glob(pattern), key=lambda item: item.name):
        if path.resolve() in expected:
            continue
        try:
            first_line = path.read_text(encoding="utf-8").splitlines()[0]
            generated = first_line in {
                GENERATED_HEADER,
                GENERATED_RESOURCE_HEADER,
            }
        except (OSError, IndexError):
            generated = False
        if not generated:
            print(f"kept non-generated file: {_relative(path)}")
            continue
        if check:
            print(f"stale generated file: {_relative(path)}")
            ok = False
        else:
            path.unlink()
            print(f"removed {_relative(path)}")
    return ok


def _scaffold_script(manifest: BossManifest) -> str:
    entry = manifest.data
    return f"""# Scaffolded by assets/source/create_boss.py. Safe to edit.
class_name {entry['class_name']}
extends BossController

const BOSS_ID := {json.dumps(entry['id'])}


func boss_id() -> String:
\treturn BOSS_ID


func definition() -> BossDefinition:
\treturn BossCatalog.definition(BOSS_ID)
"""


def _vector3_text(values: list[Any]) -> str:
    return "Vector3({})".format(
        ", ".join(_float_literal(value) for value in values)
    )


def _scaffold_scene(manifest: BossManifest) -> str:
    entry = manifest.data
    collision = entry["collision"]
    shape = collision["shape"]
    if shape == "sphere":
        shape_type = "SphereShape3D"
        shape_lines = [
            f"radius = {_float_literal(collision['radius'])}",
        ]
    elif shape == "capsule":
        shape_type = "CapsuleShape3D"
        shape_lines = [
            f"radius = {_float_literal(collision['radius'])}",
            f"height = {_float_literal(collision['height'])}",
        ]
    else:
        shape_type = "BoxShape3D"
        shape_lines = [
            f"size = {_vector3_text(collision['size'])}",
        ]
    shape_body = "\n".join(shape_lines)
    return f"""; Scaffolded by assets/source/create_boss.py. Safe to edit.
[gd_scene load_steps=4 format=3]

[ext_resource type="Script" path={json.dumps(entry['controller']['script'])} id="1_script"]
[ext_resource type="PackedScene" path={json.dumps(entry['asset']['runtime_glb'])} id="2_model"]

[sub_resource type={json.dumps(shape_type)} id="CollisionShape_boss"]
resource_local_to_scene = true
{shape_body}

[node name={json.dumps(entry['display_name'], ensure_ascii=False)} type="CharacterBody3D" groups=["bosses"]]
script = ExtResource("1_script")

[node name="CollisionShape3D" type="CollisionShape3D" parent="."]
position = {_vector3_text(collision['offset'])}
shape = SubResource("CollisionShape_boss")

[node name="Model" parent="." instance=ExtResource("2_model")]
"""


def _write_scaffold_if_absent(path: Path, content: str) -> None:
    if path.exists():
        print(f"kept existing scaffold: {_relative(path)}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        with path.open("x", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
    except FileExistsError:
        print(f"kept existing scaffold: {_relative(path)}")
        return
    print(f"scaffolded {_relative(path)}")


def scaffold(manifest: BossManifest) -> None:
    entry = manifest.data
    if entry["controller"]["mode"] != "generic":
        print(f"skipped custom controller scaffold: {manifest.boss_id}")
        return
    expected_script = (
        f"res://game/enemies/{manifest.boss_id}/{manifest.boss_id}.gd"
    )
    expected_scene = (
        f"res://game/enemies/{manifest.boss_id}/{manifest.boss_id}.tscn"
    )
    if entry["controller"]["script"] != expected_script \
            or entry["controller"]["scene"] != expected_scene:
        raise ValueError(
            f"{manifest.boss_id}: generic scaffolds must use "
            f"{expected_script} and {expected_scene}")
    _script_resource, script_path = _resource_file(
        expected_script,
        f"{manifest.boss_id}.controller.script",
        suffixes=(".gd",),
        allow_missing=True,
    )
    _scene_resource, scene_path = _resource_file(
        expected_scene,
        f"{manifest.boss_id}.controller.scene",
        suffixes=(".tscn",),
        allow_missing=True,
    )
    _write_scaffold_if_absent(script_path, _scaffold_script(manifest))
    _write_scaffold_if_absent(scene_path, _scaffold_scene(manifest))


def blender_executable() -> str:
    configured = os.environ.get("BLENDER", "").strip().strip("\"")
    if configured:
        configured_path = Path(configured)
        if configured_path.is_file():
            return str(configured_path)
        located = shutil.which(configured)
        if located:
            return located
        raise ValueError(f"BLENDER does not name an executable: {configured}")
    located = shutil.which("blender") or shutil.which("blender.exe")
    if located:
        return located
    raise ValueError(
        "Blender was requested but not found; set BLENDER or add blender "
        "to PATH")


def build_assets(manifests: list[BossManifest]) -> None:
    recipes = [
        manifest for manifest in manifests
        if Path(manifest.data["asset"]["source"]).suffix.lower() == ".blend"
    ]
    if not recipes:
        print("no .blend assets selected for building")
        return
    blender = blender_executable()
    for manifest in recipes:
        _builder_resource, builder_path = _resource_file(
            manifest.data["asset"]["builder"],
            f"{manifest.boss_id}.asset.builder",
            suffixes=(".py",),
        )
        print(f"building asset: {manifest.boss_id}")
        try:
            subprocess.run(
                [
                    blender,
                    "--background",
                    "--factory-startup",
                    "--python",
                    str(builder_path),
                ],
                cwd=ROOT,
                check=True,
            )
        except subprocess.CalledProcessError as exc:
            raise ValueError(
                f"{manifest.boss_id}: Blender builder failed with "
                f"exit code {exc.returncode}") from exc


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate versioned boss resources and catalog")
    parser.add_argument(
        "manifests",
        nargs="*",
        help="optional individual manifest paths (defaults to all)",
    )
    parser.add_argument(
        "--all",
        action="store_true",
        help="explicitly generate every non-template runtime manifest",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="report generated drift without writing",
    )
    parser.add_argument(
        "--scaffold",
        action="store_true",
        help="create missing generic controller script/scene scaffolds",
    )
    parser.add_argument(
        "--build-asset",
        action="store_true",
        help="explicitly run selected .blend asset builders",
    )
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv \
        else sys.argv[1:]
    args = parser.parse_args(argv)
    if args.all and args.manifests:
        parser.error("--all cannot be combined with individual manifests")
    if args.check and args.scaffold:
        parser.error("--check cannot be combined with --scaffold")
    if args.check and args.build_asset:
        parser.error("--check cannot be combined with --build-asset")
    return args


def run(args: argparse.Namespace) -> bool:
    default_paths = discover_manifest_paths()
    selected_paths = (
        [resolve_manifest_arg(value) for value in args.manifests]
        if args.manifests else default_paths
    )
    full_generation = not args.manifests

    catalog_paths = list(default_paths)
    known_paths = {path.resolve() for path in catalog_paths}
    for path in selected_paths:
        if path.resolve() not in known_paths:
            catalog_paths.append(path.resolve())
            known_paths.add(path.resolve())

    catalog_manifests = load_manifests(
        catalog_paths,
        allow_missing_controller=args.scaffold,
        allow_missing_runtime=args.build_asset,
    )
    selected_ids = {
        validate_manifest(
            path,
            allow_missing_controller=args.scaffold,
            allow_missing_runtime=args.build_asset,
        ).boss_id
        for path in selected_paths
    }
    selected = [
        manifest for manifest in catalog_manifests
        if manifest.boss_id in selected_ids
    ]
    if len(selected) != len(selected_ids):
        raise ValueError("selected manifest set could not be resolved")

    if args.scaffold:
        for manifest in selected:
            scaffold(manifest)
    if args.build_asset:
        build_assets(selected)

    # Revalidate after optional mutations so generated output never records a
    # scaffold or runtime model that failed to materialize.
    if args.scaffold or args.build_asset:
        catalog_manifests = load_manifests(catalog_paths)
        selected = [
            manifest for manifest in catalog_manifests
            if manifest.boss_id in selected_ids
        ]

    ok = True
    expected_definitions: set[Path] = set()
    expected_specs: set[Path] = set()
    for manifest in catalog_manifests:
        expected_definitions.add(
            (DEFINITION_DIR / f"{manifest.boss_id}.tres").resolve())
        expected_specs.add(
            (SPEC_DIR / f"{manifest.boss_id}_spec.gd").resolve())
    for manifest in selected:
        definition_path = DEFINITION_DIR / f"{manifest.boss_id}.tres"
        spec_path = SPEC_DIR / f"{manifest.boss_id}_spec.gd"
        ok = write_or_check(
            definition_path, definition_text(manifest), args.check) and ok
        ok = write_or_check(
            spec_path, spec_text(manifest), args.check) and ok
    ok = write_or_check(
        CATALOG, catalog_text(catalog_manifests), args.check) and ok

    if full_generation:
        ok = clean_or_check_stale(
            DEFINITION_DIR,
            "*.tres",
            expected_definitions,
            args.check,
        ) and ok
        ok = clean_or_check_stale(
            SPEC_DIR,
            "*_spec.gd",
            expected_specs,
            args.check,
        ) and ok
    return ok


def main() -> int:
    try:
        args = parse_args()
        return 0 if run(args) else 1
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
