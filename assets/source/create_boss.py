"""Generate deterministic Godot boss resources from versioned JSON manifests.

Run from the project root:

    python assets/source/create_boss.py
    python assets/source/create_boss.py --check
    python assets/source/create_boss.py path/to/boss.json

``--all`` explicitly selects every non-template manifest. ``--scaffold`` may
create the declared generic controller script and scene when they do not exist.
Asset recipes are never run unless ``--build-asset`` is supplied.
"""

from __future__ import annotations

import argparse
import copy
import json
import math
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any, Iterable


ROOT = Path(__file__).resolve().parents[2]
MANIFEST_DIR = ROOT / "assets/runtime/bosses/manifests"
DEFINITION_DIR = ROOT / "game/enemies/boss/definitions"
SPEC_DIR = ROOT / "game/enemies/boss/generated"
CATALOG = ROOT / "game/enemies/boss_catalog.gd"
DEFINITION_SCRIPT = "res://game/enemies/boss/boss_definition.gd"
TEMPLATE_NAME = "boss_template.json"
GENERATED_HEADER = (
    "# Generated by assets/source/create_boss.py. Do not hand-edit."
)
GENERATED_RESOURCE_HEADER = (
    "; Generated by assets/source/create_boss.py. Do not hand-edit."
)

ID_RE = re.compile(r"^[a-z][a-z0-9_]*$")
CLASS_RE = re.compile(r"^[A-Z][A-Za-z0-9]*$")
HEX_COLOR_RE = re.compile(r"^#?[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?$")
CUSTOM_NAME_RE = re.compile(r"^custom:[a-z][a-z0-9_]*$")

GENERIC_BEHAVIORS = {
    "idle",
    "chase",
    "melee",
    "projectile",
    "area",
    "charge",
    "fly",
}
REGISTERED_PRETRIGGERS = {
    "arena_entry",
    "desert_flyby",
    "caldera_run",
}
CONTROLLER_MODES = {"custom", "generic"}
LOCATION_MODES = {"planet_surface", "world_space"}
DISTANCE_MODES = {"surface_arc", "euclidean"}
COLLISION_SHAPES = {"sphere", "capsule", "box"}


@dataclass(frozen=True)
class BossManifest:
    path: Path
    data: dict[str, Any]

    @property
    def boss_id(self) -> str:
        return str(self.data["id"])


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key!r}")
        result[key] = value
    return result


def read_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(
            path.read_text(encoding="utf-8"),
            object_pairs_hook=_unique_object,
        )
    except FileNotFoundError as exc:
        raise ValueError(f"manifest does not exist: {_relative(path)}") from exc
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"cannot read {_relative(path)}: {exc}") from exc
    if not isinstance(value, dict):
        raise ValueError(f"{_relative(path)}: manifest root must be an object")
    return value


def _relative(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except (OSError, ValueError):
        return str(path)


def _check_keys(
    value: dict[str, Any],
    *,
    required: Iterable[str],
    allowed: Iterable[str],
    label: str,
) -> None:
    required_set = set(required)
    allowed_set = set(allowed)
    missing = sorted(required_set.difference(value))
    if missing:
        raise ValueError(f"{label}: missing {', '.join(missing)}")
    unknown = sorted(set(value).difference(allowed_set))
    if unknown:
        raise ValueError(f"{label}: unknown field(s) {', '.join(unknown)}")


def _required_object(value: Any, label: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ValueError(f"{label} must be an object")
    return value


def _required_list(value: Any, label: str) -> list[Any]:
    if not isinstance(value, list):
        raise ValueError(f"{label} must be an array")
    return value


def _required_string(value: Any, label: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{label} must be a non-empty string")
    return value


def _finite_number(value: Any, label: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{label} must be a finite number")
    result = float(value)
    if not math.isfinite(result):
        raise ValueError(f"{label} must be a finite number")
    return result


def _positive_number(value: Any, label: str) -> float:
    result = _finite_number(value, label)
    if result <= 0.0:
        raise ValueError(f"{label} must be greater than zero")
    return result


def _vector3(value: Any, label: str, *, positive: bool = False) -> list[float]:
    row = _required_list(value, label)
    if len(row) != 3:
        raise ValueError(f"{label} must contain exactly three numbers")
    result = [_finite_number(component, f"{label}[{index}]")
              for index, component in enumerate(row)]
    if positive and any(component <= 0.0 for component in result):
        raise ValueError(f"{label} dimensions must be greater than zero")
    return result


def _validate_json_safe(value: Any, label: str) -> None:
    if value is None or isinstance(value, (str, bool)):
        return
    if isinstance(value, int):
        if value < -(2**63) or value > 2**63 - 1:
            raise ValueError(f"{label} integer is outside Godot's 64-bit range")
        return
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError(f"{label} must not contain NaN or infinity")
        return
    if isinstance(value, list):
        for index, item in enumerate(value):
            _validate_json_safe(item, f"{label}[{index}]")
        return
    if isinstance(value, dict):
        for key, item in value.items():
            if not isinstance(key, str):
                raise ValueError(f"{label} object keys must be strings")
            _validate_json_safe(item, f"{label}.{key}")
        return
    raise ValueError(
        f"{label} contains unsupported JSON value {type(value).__name__}")


def _resource_file(
    value: Any,
    label: str,
    *,
    suffixes: tuple[str, ...] = (),
    allow_missing: bool = False,
) -> tuple[str, Path]:
    resource_path = _required_string(value, label).replace("\\", "/")
    if not resource_path.startswith("res://"):
        raise ValueError(f"{label} must be a res:// project path")
    relative = PurePosixPath(resource_path.removeprefix("res://"))
    if relative.is_absolute() or not relative.parts \
            or any(part in ("", ".", "..") for part in relative.parts):
        raise ValueError(f"{label} contains an invalid project path")
    disk_path = ROOT.joinpath(*relative.parts)
    if suffixes and disk_path.suffix.lower() not in suffixes:
        expected = ", ".join(suffixes)
        raise ValueError(f"{label} must end in one of: {expected}")
    if not allow_missing and not disk_path.is_file():
        raise ValueError(f"{label} is missing: {resource_path}")
    return resource_path, disk_path


def _animation_contract(
    value: Any,
    boss_id: str,
) -> tuple[dict[str, Any], set[str]]:
    animations = _required_object(value, f"{boss_id}.animations")
    if not animations:
        raise ValueError(f"{boss_id}.animations must not be empty")
    clips: set[str] = set()
    for role, mapping in animations.items():
        if not isinstance(role, str) or not ID_RE.fullmatch(role):
            raise ValueError(f"{boss_id}.animations has invalid role {role!r}")
        if isinstance(mapping, str):
            clips.add(_required_string(
                mapping, f"{boss_id}.animations.{role}"))
            continue
        subroles = _required_object(
            mapping, f"{boss_id}.animations.{role}")
        if not subroles:
            raise ValueError(
                f"{boss_id}.animations.{role} must not be empty")
        for subrole, clip in subroles.items():
            if not isinstance(subrole, str) or not ID_RE.fullmatch(subrole):
                raise ValueError(
                    f"{boss_id}.animations.{role} has invalid subrole "
                    f"{subrole!r}")
            clips.add(_required_string(
                clip, f"{boss_id}.animations.{role}.{subrole}"))
    rest = animations.get("rest")
    if not isinstance(rest, str) or not rest.strip():
        raise ValueError(f"{boss_id}: animations.rest must name a clip")
    return animations, clips


def _validate_moves(
    value: Any,
    boss_id: str,
    controller_mode: str,
    known_clips: set[str],
) -> list[dict[str, Any]]:
    moves = _required_list(value, f"{boss_id}.moves")
    if not moves:
        raise ValueError(f"{boss_id}.moves must not be empty")
    seen: set[str] = set()
    for index, raw_move in enumerate(moves):
        label = f"{boss_id}.moves[{index}]"
        move = _required_object(raw_move, label)
        _check_keys(
            move,
            required=("id", "behavior", "animations"),
            allowed=("id", "behavior", "animations", "parameters"),
            label=label,
        )
        move_id = _required_string(move["id"], f"{label}.id")
        if not ID_RE.fullmatch(move_id):
            raise ValueError(f"{label}.id is invalid: {move_id!r}")
        if move_id in seen:
            raise ValueError(f"{boss_id}: duplicate move id {move_id!r}")
        seen.add(move_id)

        behavior = _required_string(move["behavior"], f"{label}.behavior")
        built_in = behavior in GENERIC_BEHAVIORS
        custom = bool(CUSTOM_NAME_RE.fullmatch(behavior))
        if controller_mode == "generic" and not built_in:
            raise ValueError(
                f"{label}.behavior {behavior!r} is not registered for "
                "generic controllers")
        if controller_mode == "custom" and not (built_in or custom):
            raise ValueError(
                f"{label}.behavior must be built-in or use custom:<id>")

        mappings = _required_object(
            move["animations"], f"{label}.animations")
        if not mappings:
            raise ValueError(f"{label}.animations must not be empty")
        for stage, clip_value in mappings.items():
            if not isinstance(stage, str) or not ID_RE.fullmatch(stage):
                raise ValueError(
                    f"{label}.animations has invalid stage {stage!r}")
            clip = _required_string(
                clip_value, f"{label}.animations.{stage}")
            if clip not in known_clips:
                raise ValueError(
                    f"{label}.animations.{stage} maps unknown clip {clip!r}")
        if "parameters" in move:
            parameters = _required_object(
                move["parameters"], f"{label}.parameters")
            _validate_json_safe(parameters, f"{label}.parameters")
    return moves


def _validate_pretriggers(value: Any, boss_id: str) -> list[str]:
    raw_names = _required_list(value, f"{boss_id}.pretriggers")
    result: list[str] = []
    seen: set[str] = set()
    for index, raw_name in enumerate(raw_names):
        name = _required_string(
            raw_name, f"{boss_id}.pretriggers[{index}]")
        if name not in REGISTERED_PRETRIGGERS \
                and not CUSTOM_NAME_RE.fullmatch(name):
            raise ValueError(
                f"{boss_id}.pretriggers[{index}] has malformed or "
                f"unregistered name {name!r}")
        if name in seen:
            raise ValueError(f"{boss_id}: duplicate pretrigger {name!r}")
        seen.add(name)
        result.append(name)
    return result


def _validate_location(
    value: Any,
    boss_id: str,
    distance_mode: str,
) -> dict[str, Any]:
    location = _required_object(value, f"{boss_id}.location")
    mode = _required_string(location.get("mode"), f"{boss_id}.location.mode")
    if mode not in LOCATION_MODES:
        raise ValueError(f"{boss_id}.location.mode is invalid: {mode!r}")
    if mode == "planet_surface":
        _check_keys(
            location,
            required=("mode", "direction", "facing", "clearance"),
            allowed=("mode", "direction", "facing", "clearance"),
            label=f"{boss_id}.location",
        )
        direction = _vector3(
            location["direction"], f"{boss_id}.location.direction")
        length = math.sqrt(sum(component * component
                               for component in direction))
        if length <= 1.0e-6 or abs(length - 1.0) > 1.0e-3:
            raise ValueError(
                f"{boss_id}.location.direction must be a unit vector")
        _finite_number(location["facing"], f"{boss_id}.location.facing")
        clearance = _finite_number(
            location["clearance"], f"{boss_id}.location.clearance")
        if clearance < 0.0:
            raise ValueError(
                f"{boss_id}.location.clearance must not be negative")
        if distance_mode != "surface_arc":
            raise ValueError(
                f"{boss_id}: planet_surface requires surface_arc distance")
    else:
        _check_keys(
            location,
            required=("mode", "parent", "origin", "orientation"),
            allowed=("mode", "parent", "origin", "orientation"),
            label=f"{boss_id}.location",
        )
        _required_string(
            location["parent"], f"{boss_id}.location.parent")
        _vector3(location["origin"], f"{boss_id}.location.origin")
        _vector3(
            location["orientation"], f"{boss_id}.location.orientation")
        if distance_mode != "euclidean":
            raise ValueError(
                f"{boss_id}: world_space requires euclidean distance")
    return location


def _validate_waypoint(value: Any, boss_id: str) -> dict[str, Any]:
    waypoint = _required_object(value, f"{boss_id}.waypoint")
    _check_keys(
        waypoint,
        required=(
            "enabled",
            "title",
            "tint",
            "show_beyond",
            "aimed_beyond",
            "hide_beyond",
        ),
        allowed=(
            "enabled",
            "title",
            "tint",
            "show_beyond",
            "aimed_beyond",
            "hide_beyond",
        ),
        label=f"{boss_id}.waypoint",
    )
    if not isinstance(waypoint["enabled"], bool):
        raise ValueError(f"{boss_id}.waypoint.enabled must be a boolean")
    _required_string(waypoint["title"], f"{boss_id}.waypoint.title")
    tint = _required_string(waypoint["tint"], f"{boss_id}.waypoint.tint")
    if not HEX_COLOR_RE.fullmatch(tint):
        raise ValueError(f"{boss_id}.waypoint.tint must be RGB or RGBA hex")
    for key in ("show_beyond", "aimed_beyond", "hide_beyond"):
        amount = _finite_number(
            waypoint[key], f"{boss_id}.waypoint.{key}")
        if amount < 0.0:
            raise ValueError(
                f"{boss_id}.waypoint.{key} must not be negative")
    return waypoint


def validate_manifest(
    path: Path,
    *,
    allow_missing_controller: bool = False,
    allow_missing_runtime: bool = False,
) -> BossManifest:
    raw = read_json(path)
    data = copy.deepcopy(raw)
    if data.get("template") is True:
        raise ValueError(f"{_relative(path)} is a template, not a runtime boss")
    _check_keys(
        data,
        required=(
            "version",
            "id",
            "class_name",
            "display_name",
            "description",
            "asset",
            "controller",
            "health",
            "arena",
            "combat",
            "collision",
            "animations",
            "moves",
            "pretriggers",
            "location",
            "waypoint",
        ),
        allowed=(
            "version",
            "template",
            "id",
            "class_name",
            "display_name",
            "description",
            "asset",
            "controller",
            "health",
            "arena",
            "combat",
            "collision",
            "animations",
            "moves",
            "pretriggers",
            "location",
            "waypoint",
            "material",
            "tags",
            "extensions",
        ),
        label=_relative(path),
    )
    if isinstance(data["version"], bool) or data["version"] != 1:
        raise ValueError(f"{_relative(path)}: version must be 1")
    if "template" in data and not isinstance(data["template"], bool):
        raise ValueError(f"{_relative(path)}: template must be a boolean")

    boss_id = _required_string(data["id"], f"{_relative(path)}.id")
    if not ID_RE.fullmatch(boss_id):
        raise ValueError(f"{_relative(path)}: invalid boss id {boss_id!r}")
    class_name = _required_string(
        data["class_name"], f"{boss_id}.class_name")
    if not CLASS_RE.fullmatch(class_name):
        raise ValueError(f"{boss_id}: invalid class_name {class_name!r}")
    _required_string(data["display_name"], f"{boss_id}.display_name")
    _required_string(data["description"], f"{boss_id}.description")

    asset = _required_object(data["asset"], f"{boss_id}.asset")
    _check_keys(
        asset,
        required=("source",),
        allowed=("source", "runtime_glb", "builder"),
        label=f"{boss_id}.asset",
    )
    source, source_path = _resource_file(
        asset["source"],
        f"{boss_id}.asset.source",
        suffixes=(".blend", ".glb"),
    )
    if source_path.suffix.lower() == ".blend":
        if "runtime_glb" not in asset or "builder" not in asset:
            raise ValueError(
                f"{boss_id}: a .blend source requires asset.builder and "
                "asset.runtime_glb")
        runtime_glb, _runtime_path = _resource_file(
            asset["runtime_glb"],
            f"{boss_id}.asset.runtime_glb",
            suffixes=(".glb",),
            allow_missing=allow_missing_runtime,
        )
        builder, _builder_path = _resource_file(
            asset["builder"],
            f"{boss_id}.asset.builder",
            suffixes=(".py",),
        )
        asset["runtime_glb"] = runtime_glb
        asset["builder"] = builder
    else:
        runtime_value = asset.get("runtime_glb", source)
        runtime_glb, _runtime_path = _resource_file(
            runtime_value,
            f"{boss_id}.asset.runtime_glb",
            suffixes=(".glb",),
        )
        asset["runtime_glb"] = runtime_glb
        if "builder" in asset:
            builder, _builder_path = _resource_file(
                asset["builder"],
                f"{boss_id}.asset.builder",
                suffixes=(".py",),
            )
            asset["builder"] = builder
    asset["source"] = source

    controller = _required_object(
        data["controller"], f"{boss_id}.controller")
    _check_keys(
        controller,
        required=("mode", "scene", "script"),
        allowed=("mode", "scene", "script"),
        label=f"{boss_id}.controller",
    )
    controller_mode = _required_string(
        controller["mode"], f"{boss_id}.controller.mode")
    if controller_mode not in CONTROLLER_MODES:
        raise ValueError(
            f"{boss_id}.controller.mode is invalid: {controller_mode!r}")
    scene, _scene_path = _resource_file(
        controller["scene"],
        f"{boss_id}.controller.scene",
        suffixes=(".tscn",),
        allow_missing=allow_missing_controller and controller_mode == "generic",
    )
    script, _script_path = _resource_file(
        controller["script"],
        f"{boss_id}.controller.script",
        suffixes=(".gd",),
        allow_missing=allow_missing_controller and controller_mode == "generic",
    )
    controller["scene"] = scene
    controller["script"] = script

    _positive_number(data["health"], f"{boss_id}.health")

    arena = _required_object(data["arena"], f"{boss_id}.arena")
    _check_keys(
        arena,
        required=(
            "radius",
            "detection_radius",
            "reset_delay",
            "distance_mode",
        ),
        allowed=(
            "radius",
            "detection_radius",
            "reset_delay",
            "distance_mode",
        ),
        label=f"{boss_id}.arena",
    )
    _positive_number(arena["radius"], f"{boss_id}.arena.radius")
    _positive_number(
        arena["detection_radius"], f"{boss_id}.arena.detection_radius")
    _positive_number(
        arena["reset_delay"], f"{boss_id}.arena.reset_delay")
    distance_mode = _required_string(
        arena["distance_mode"], f"{boss_id}.arena.distance_mode")
    if distance_mode not in DISTANCE_MODES:
        raise ValueError(
            f"{boss_id}.arena.distance_mode is invalid: {distance_mode!r}")

    combat = _required_object(data["combat"], f"{boss_id}.combat")
    _check_keys(
        combat,
        required=("radius", "center_height"),
        allowed=("radius", "center_height"),
        label=f"{boss_id}.combat",
    )
    _positive_number(combat["radius"], f"{boss_id}.combat.radius")
    _positive_number(
        combat["center_height"], f"{boss_id}.combat.center_height")

    collision = _required_object(
        data["collision"], f"{boss_id}.collision")
    shape = _required_string(
        collision.get("shape"), f"{boss_id}.collision.shape")
    if shape not in COLLISION_SHAPES:
        raise ValueError(
            f"{boss_id}.collision.shape is invalid: {shape!r}")
    if shape == "sphere":
        _check_keys(
            collision,
            required=("shape", "radius", "offset"),
            allowed=("shape", "radius", "offset"),
            label=f"{boss_id}.collision",
        )
        _positive_number(
            collision["radius"], f"{boss_id}.collision.radius")
    elif shape == "capsule":
        _check_keys(
            collision,
            required=("shape", "radius", "height", "offset"),
            allowed=("shape", "radius", "height", "offset"),
            label=f"{boss_id}.collision",
        )
        _positive_number(
            collision["radius"], f"{boss_id}.collision.radius")
        _positive_number(
            collision["height"], f"{boss_id}.collision.height")
    else:
        _check_keys(
            collision,
            required=("shape", "size", "offset"),
            allowed=("shape", "size", "offset"),
            label=f"{boss_id}.collision",
        )
        _vector3(
            collision["size"], f"{boss_id}.collision.size", positive=True)
    _vector3(collision["offset"], f"{boss_id}.collision.offset")

    animations, clips = _animation_contract(data["animations"], boss_id)
    data["animations"] = animations
    data["moves"] = _validate_moves(
        data["moves"], boss_id, controller_mode, clips)
    data["pretriggers"] = _validate_pretriggers(
        data["pretriggers"], boss_id)
    data["location"] = _validate_location(
        data["location"], boss_id, distance_mode)
    data["waypoint"] = _validate_waypoint(data["waypoint"], boss_id)

    if "material" in data:
        material, _material_path = _resource_file(
            data["material"],
            f"{boss_id}.material",
            suffixes=(".tres", ".material"),
        )
        data["material"] = material

    tags = data.get("tags", [])
    tags = _required_list(tags, f"{boss_id}.tags")
    seen_tags: set[str] = set()
    for index, raw_tag in enumerate(tags):
        tag = _required_string(raw_tag, f"{boss_id}.tags[{index}]")
        if not ID_RE.fullmatch(tag):
            raise ValueError(f"{boss_id}: invalid tag {tag!r}")
        if tag in seen_tags:
            raise ValueError(f"{boss_id}: duplicate tag {tag!r}")
        seen_tags.add(tag)
    data["tags"] = tags

    extensions = data.get("extensions", {})
    data["extensions"] = _required_object(
        extensions, f"{boss_id}.extensions")
    return BossManifest(path.resolve(), data)


def discover_manifest_paths() -> list[Path]:
    if not MANIFEST_DIR.is_dir():
        raise ValueError(
            f"manifest directory is missing: {_relative(MANIFEST_DIR)}")
    result: list[Path] = []
    for path in sorted(MANIFEST_DIR.glob("*.json"), key=lambda item: item.name):
        raw = read_json(path)
        if path.name == TEMPLATE_NAME or raw.get("template") is True:
            continue
        result.append(path.resolve())
    if not result:
        raise ValueError("no runtime boss manifests found")
    return result


def resolve_manifest_arg(value: str) -> Path:
    if value.replace("\\", "/").startswith("res://"):
        _resource, path = _resource_file(
            value, "manifest", suffixes=(".json",))
        return path.resolve()
    path = Path(value)
    if not path.is_absolute():
        path = ROOT / path
    if path.suffix.lower() != ".json":
        raise ValueError(f"manifest must be a .json file: {value}")
    if not path.is_file():
        raise ValueError(f"manifest does not exist: {_relative(path)}")
    return path.resolve()


def load_manifests(
    paths: Iterable[Path],
    *,
    allow_missing_controller: bool = False,
    allow_missing_runtime: bool = False,
) -> list[BossManifest]:
    manifests = [
        validate_manifest(
            path,
            allow_missing_controller=allow_missing_controller,
            allow_missing_runtime=allow_missing_runtime,
        )
        for path in paths
    ]
    seen: dict[str, Path] = {}
    for manifest in manifests:
        previous = seen.get(manifest.boss_id)
        if previous is not None:
            raise ValueError(
                f"duplicate manifest id {manifest.boss_id!r}: "
                f"{_relative(previous)} and {_relative(manifest.path)}")
        seen[manifest.boss_id] = manifest.path
    return sorted(manifests, key=lambda item: item.boss_id)


def _godot_literal(value: Any) -> str:
    return json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        indent=2,
        allow_nan=False,
    )


def _float_literal(value: Any) -> str:
    number = float(value)
    if number == 0.0:
        number = 0.0
    result = repr(number)
    return result if "." in result or "e" in result.lower() else result + ".0"


def _packed_strings(values: list[str]) -> str:
    return "PackedStringArray({})".format(
        ", ".join(json.dumps(value, ensure_ascii=False) for value in values)
    )


def definition_text(manifest: BossManifest) -> str:
    entry = manifest.data
    ext_resources = [
        (
            "Script",
            DEFINITION_SCRIPT,
            "1_definition",
        ),
        (
            "PackedScene",
            entry["controller"]["scene"],
            "2_scene",
        ),
        (
            "Script",
            entry["controller"]["script"],
            "3_controller",
        ),
        (
            "PackedScene",
            entry["asset"]["runtime_glb"],
            "4_model",
        ),
    ]
    material_id = ""
    if entry.get("material"):
        material_id = "5_material"
        ext_resources.append(("Material", entry["material"], material_id))

    lines = [
        GENERATED_RESOURCE_HEADER,
        (
            "[gd_resource type=\"Resource\" script_class=\"BossDefinition\" "
            f"load_steps={len(ext_resources) + 1} format=3]"
        ),
        "",
    ]
    for kind, path, resource_id in ext_resources:
        lines.append(
            f"[ext_resource type={json.dumps(kind)} "
            f"path={json.dumps(path, ensure_ascii=False)} "
            f"id={json.dumps(resource_id)}]"
        )
    lines.extend(
        [
            "",
            "[resource]",
            "script = ExtResource(\"1_definition\")",
            f"boss_id = {json.dumps(entry['id'])}",
            f"boss_class_name = {json.dumps(entry['class_name'])}",
            f"display_name = {json.dumps(entry['display_name'], ensure_ascii=False)}",
            f"description = {json.dumps(entry['description'], ensure_ascii=False)}",
            f"controller_mode = &{json.dumps(entry['controller']['mode'])}",
            "boss_scene = ExtResource(\"2_scene\")",
            "controller_script = ExtResource(\"3_controller\")",
            "runtime_model = ExtResource(\"4_model\")",
            f"asset = {_godot_literal(entry['asset'])}",
            f"max_health = {_float_literal(entry['health'])}",
            f"arena_radius = {_float_literal(entry['arena']['radius'])}",
            (
                "detection_radius = "
                f"{_float_literal(entry['arena']['detection_radius'])}"
            ),
            f"reset_delay = {_float_literal(entry['arena']['reset_delay'])}",
            f"arena_distance_mode = &{json.dumps(entry['arena']['distance_mode'])}",
            f"combat = {_godot_literal(entry['combat'])}",
            f"collision = {_godot_literal(entry['collision'])}",
            f"animations = {_godot_literal(entry['animations'])}",
            f"moves = {_godot_literal(entry['moves'])}",
            f"pretriggers = {_packed_strings(entry['pretriggers'])}",
            f"location = {_godot_literal(entry['location'])}",
            f"waypoint = {_godot_literal(entry['waypoint'])}",
        ]
    )
    if material_id:
        lines.append(f"material_override = ExtResource({json.dumps(material_id)})")
    lines.extend(
        [
            f"tags = {_packed_strings(entry['tags'])}",
            f"extensions = {_godot_literal(entry['extensions'])}",
            "",
        ]
    )
    return "\n".join(lines)


